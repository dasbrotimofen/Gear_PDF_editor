import * as esbuild from 'esbuild';
const options = {
  entryPoints: ['src/main.ts'], bundle: true, external: ['obsidian'],
  platform: 'browser', format: 'cjs', target: 'es2020', outfile: 'main.js',
  banner: { js: '// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by npm run build; source in src/.' },
};
if (process.argv.includes('--watch')) {
  const context = await esbuild.context(options);
  await context.watch();
} else await esbuild.build(options);
